window.flattenSectorTree = function() {
  const out = {};
  const tree = window.SECTOR_TREE || {};
  Object.keys(tree).forEach(main => {
    out[main] = [];
    Object.keys(tree[main] || {}).forEach(sub => {
      out[main].push(sub);
      (tree[main][sub] || []).forEach(micro => out[main].push(micro));
    });
    out[main] = [...new Set(out[main])];
  });
  return out;
};
window.SECTOR_DATA = window.flattenSectorTree();

